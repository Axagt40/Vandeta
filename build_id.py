"""Generate the build identity header (task 1, phase 4).

Runs as a PlatformIO `pre:` extra script, so the header exists before any TU is
compiled. It writes:

    src/core/dev/vnd_build_info.h   - version, build ID, folded 8-byte ID
    vnd_build_id.txt                - the same ID for host tools

The ID is `<git short sha>[-dirty]-<UTC timestamp>`. Outside a git checkout it
falls back to `nogit-<timestamp>`, which still changes every build, so a stale
payload can never be accepted by accident.

The version string lives in version.txt (one line). That file is the only input
a release bump touches, and because just build_info.cpp includes the generated
header, the rebuild is one object instead of the whole tree.
"""
import subprocess
import time
from pathlib import Path

from SCons.Script import Import

Import("env")

proj = Path(env.subst("$PROJECT_DIR"))
out_dir = proj / "src" / "core" / "dev"
out_h = out_dir / "vnd_build_info.h"
out_txt = proj / "vnd_build_id.txt"

version_file = proj / "version.txt"
version = "vandeta 1.4-pre"
if version_file.exists():
    text = version_file.read_text(encoding="utf-8").strip()
    if text:
        version = text

sha = "nogit"
dirty = False
try:
    sha = subprocess.check_output(
        ["git", "-c", "safe.directory=*", "rev-parse", "--short=8", "HEAD"],
        cwd=str(proj), stderr=subprocess.DEVNULL, text=True,
    ).strip() or "nogit"
    status = subprocess.check_output(
        ["git", "-c", "safe.directory=*", "status", "--porcelain"],
        cwd=str(proj), stderr=subprocess.DEVNULL, text=True,
    )
    dirty = bool(status.strip())
except Exception:
    sha = "nogit"

stamp = time.strftime("%Y%m%d-%H%M%S", time.gmtime())
build_id = f"{sha}{'-dirty' if dirty else ''}-{stamp}"


def fnv1a64(data: bytes) -> int:
    h = 1469598103934665603
    for b in data:
        h ^= b
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h or 1


folded = fnv1a64(build_id.encode())

body = f"""// Generated by build_id.py - do not edit, do not include from another TU.
#ifndef __CORE_DEV_VND_BUILD_INFO_H__
#define __CORE_DEV_VND_BUILD_INFO_H__
#define VND_VERSION_STR "{version}"
#define VND_BUILD_ID_STR "{build_id}"
#define VND_BUILD_ID_FNV 0x{folded:016X}ULL
#define VND_BUILD_ID_DIRTY {1 if dirty else 0}
#endif
"""

out_dir.mkdir(parents=True, exist_ok=True)
old = out_h.read_text(encoding="utf-8") if out_h.exists() else None
if old != body:
    out_h.write_text(body, encoding="utf-8")
out_txt.write_text(build_id + "\n", encoding="utf-8")

print(f"[build_id] version={version} build={build_id}")
