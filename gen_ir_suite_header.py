#!/usr/bin/env python3
"""Embed the Vandeta IR Suite script into the firmware image.

The suite is a JavaScript program for the on-device interpreter. Shipping it on
the SD card made it a separate thing to copy and a separate thing to keep in
sync; it now lives in the firmware itself and is opened from `IR > IR Suite`.

This pre-build step turns

    src/modules/ir/ir_suite_src/Vandeta_IR_Suite.js

into

    src/modules/ir/ir_suite_script.h        (a raw string literal in .rodata)

which `src/modules/ir/ir_suite.cpp` copies into PSRAM and hands to the
interpreter. The header is regenerated only when the script changes, so an
untouched script does not force a rebuild.
"""
import os

# PlatformIO runs extra_scripts with exec(), where __file__ is not defined -
# take the project root from the SCons env (the same way patch.py does).
try:
    Import("env")  # noqa: F821 - injected by SCons
    PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821
except Exception:  # run by hand / from a plain python shell
    PROJECT = os.getcwd()
PROJECT = os.path.abspath(PROJECT)
SRC = os.path.join(PROJECT, "src", "modules", "ir", "ir_suite_src", "Vandeta_IR_Suite.js")
OUT = os.path.join(PROJECT, "src", "modules", "ir", "ir_suite_script.h")

DELIM_OPEN = 'R"VNDIRSUITE('
DELIM_CLOSE = ')VNDIRSUITE"'

HEADER = """// GENERATED FILE - do not edit.
// Source: src/modules/ir/ir_suite_src/Vandeta_IR_Suite.js
// Generated by gen_ir_suite_header.py (a PlatformIO pre-build step).
#pragma once
#include <Arduino.h>

static const char IR_SUITE_JS[] PROGMEM = {open}
{body}
{close};

static const size_t IR_SUITE_JS_LEN = sizeof(IR_SUITE_JS) - 1;
"""


def main():
    with open(SRC, "r", encoding="utf-8", newline="\n") as f:
        body = f.read()

    # A raw string cannot contain its own closing sequence.
    if DELIM_CLOSE in body:
        raise SystemExit("gen_ir_suite_header: the script contains the raw-string delimiter")

    new = HEADER.format(open=DELIM_OPEN, body=body, close=DELIM_CLOSE)

    if os.path.exists(OUT):
        with open(OUT, "r", encoding="utf-8", newline="\n") as f:
            if f.read() == new:
                print("[ir suite] header unchanged (%d bytes of script)" % len(body))
                return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print("[ir suite] embedded %s -> ir_suite_script.h (%d bytes)" % (os.path.basename(SRC), len(body)))


main()
