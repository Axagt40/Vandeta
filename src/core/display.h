// --- Task 06: navigation breadcrumb -------------------------------------------
// A fixed-size (no per-menu heap growth) stack of the titles of the menus that
// are currently open, deepest last. loopOptions() pushes on entry and pops on
// exit; drawSubmenu() renders it as the "A > B > C" breadcrumb. Nav history and
// Back are unchanged in this demo shell - only the visible path is drawn.
#define NAV_PATH_MAX 10
void navPushMenu(const char *title, uint8_t menuType);
void navPopMenu(void);
void navResetMenu(void);

// The vector of the menu currently on screen, or the global `options` when no
// menu is open. Serial readback (ui/move/press, UISTATE, ui watch) uses this so
// it works for menus built with a local vector too.
inline std::vector<Option> &activeMenuOptions() {
    return activeOptions ? *activeOptions : options;
}

// Published to `activeOptions` for the whole time the menu is on screen (nested
// menus restore their parent's vector on exit) and cleared when it closes.
inline int loopOptions(
    std::vector<Option> &options, uint8_t menuType, const char *subText, int index = 0,
    bool interpreter = false
) {
    std::vector<Option> *prev = activeOptions;
    activeOptions = &options;
    navPushMenu(subText, menuType);
    int ret = loopOptionsImpl(options, menuType, subText, index, interpreter);
    navPopMenu();
    activeOptions = prev;
    return ret;
}
inline int loopOptions(std::vector<Option> &options, int _index) {
    return loopOptions(options, MENU_TYPE_REGULAR, "", _index, false);
}
inline int loopOptions(std::vector<Option> &options) {
    return loopOptions(options, MENU_TYPE_REGULAR, "", 0, false);
}

